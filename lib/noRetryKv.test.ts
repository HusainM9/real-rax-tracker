import { afterEach, beforeEach, expect, it, vi } from 'vitest'
vi.unmock('./noRetryKv')
vi.unmock('@vercel/kv')

beforeEach(() => {
  vi.resetModules()
  vi.stubEnv('KV_REST_API_URL', 'https://offline.invalid')
  vi.stubEnv('KV_REST_API_TOKEN', 'fixture-token')
  vi.spyOn(console, 'error').mockImplementation(() => {})
})
afterEach(() => vi.restoreAllMocks())

it('makes exactly one HTTP attempt through the real SDK after a lost connection', async () => {
  const fetcher = vi.fn().mockRejectedValue(new TypeError('Fixture lost connection'))
  vi.stubGlobal('fetch', fetcher)
  const { kv } = await import('./noRetryKv')
  await expect(kv.get('cache')).rejects.toMatchObject({ retryable: false })
  expect(fetcher).toHaveBeenCalledTimes(1)
})
it('preserves a real HTTP 503 before SDK error conversion and stops later storage HTTP', async () => {
  const fetcher = vi.fn().mockResolvedValue(Response.json({ error: 'private provider response' }, { status: 503 }))
  vi.stubGlobal('fetch', fetcher)
  const { kv } = await import('./noRetryKv')
  await expect(kv.get('cache')).rejects.toMatchObject({ upstreamStatus: 503, retryable: false })
  expect(() => kv.set('unrelated', 'value')).toThrow()
  expect(fetcher).toHaveBeenCalledTimes(1)
  expect(console.error).toHaveBeenCalledWith('request-safety incident', expect.objectContaining({ provider: 'kv', status: 503, action: 'paused_until_review' }))
  expect(JSON.stringify(vi.mocked(console.error).mock.calls)).not.toMatch(/private provider response|fixture-token|offline\.invalid/)
})
it('does not turn an HTTP-200 Redis command error into a global storage outage', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(Response.json({ error: 'WRONGTYPE private-key' })).mockResolvedValue(Response.json({ result: 1 }))
  vi.stubGlobal('fetch', fetcher)
  const { kv } = await import('./noRetryKv')
  await expect(kv.get('wrong-type')).rejects.toThrow()
  await expect(kv.exists('unrelated-key')).resolves.toBe(1)
  expect(fetcher).toHaveBeenCalledTimes(2)
})
it('retains an uncertain exact storage command without poisoning unrelated commands', async () => {
  const fetcher = vi.fn().mockRejectedValueOnce(new TypeError('Fixture network failure')).mockResolvedValue(Response.json({ result: 1 }))
  vi.stubGlobal('fetch', fetcher)
  const { kv } = await import('./noRetryKv')
  await expect(kv.get('cache')).rejects.toMatchObject({ retryable: false })
  await expect(kv.get('cache')).rejects.toMatchObject({ retryable: false })
  expect(fetcher).toHaveBeenCalledTimes(1)
  await expect(kv.exists('unrelated-key')).resolves.toBe(1)
  expect(fetcher).toHaveBeenCalledTimes(2)
})
it('guards real SDK pipeline transport and preserves its HTTP 502', async () => {
  const fetcher = vi.fn().mockResolvedValue(Response.json({ error: 'gateway failure' }, { status: 502 }))
  vi.stubGlobal('fetch', fetcher)
  const { kv } = await import('./noRetryKv')
  await expect(kv.pipeline().get('cache').exec()).rejects.toMatchObject({ upstreamStatus: 502, retryable: false })
  expect(() => kv.get('other')).toThrow()
  expect(fetcher).toHaveBeenCalledTimes(1)
})
it('does not poison unrelated commands after a pipeline command error in HTTP 200', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(Response.json([{ error: 'WRONGTYPE private-key' }])).mockResolvedValue(Response.json({ result: 1 }))
  vi.stubGlobal('fetch', fetcher)
  const { kv } = await import('./noRetryKv')
  await expect(kv.pipeline().get('wrong-type').exec()).rejects.toThrow()
  await expect(kv.exists('unrelated-key')).resolves.toBe(1)
  expect(fetcher).toHaveBeenCalledTimes(2)
})
it('keeps SDK pipeline serialization and JSON deserialization with one guarded HTTP call', async () => {
  const fetcher = vi.fn().mockResolvedValue(Response.json([{ result: 'OK' }, { result: '{"rows":[1]}' }]))
  vi.stubGlobal('fetch', fetcher)
  const { kv } = await import('./noRetryKv')
  await expect(kv.pipeline().set('fixture', { rows: [1] }).get('fixture').exec()).resolves.toEqual(['OK', { rows: [1] }])
  expect(fetcher).toHaveBeenCalledTimes(1)
  const [url, init] = fetcher.mock.calls[0]!
  expect(url).toBe('https://offline.invalid/pipeline')
  expect(init).toMatchObject({ method: 'POST', redirect: 'error', cache: 'no-store' })
  expect(JSON.parse(init.body)).toEqual([['set', 'fixture', '{"rows":[1]}'], ['get', 'fixture']])
})
